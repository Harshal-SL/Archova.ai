"""Pydantic Contracts for Architecture Delta Versioning and Evolution."""

from __future__ import annotations

from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field, model_validator


# ── Allowed Additive Modifications on Existing Entities ──

class ColumnAddition(BaseModel):
    """Additive modification: adding a column to an existing table."""
    table_name: str = Field(..., description="Name of the existing table")
    column_name: str = Field(..., description="Name of the new column")
    column_type: str = Field(..., description="Postgres/SQL data type")
    nullable: bool = Field(default=True, description="Must be true if no default is provided")
    default: Optional[str] = Field(default=None, description="Default value expression if not nullable")
    references: Optional[str] = Field(default=None, description="e.g. 'users(id)' for foreign key")


class ExistingServiceEndpointAddition(BaseModel):
    """Additive modification: adding an endpoint to an existing service."""
    service_id_or_name: str = Field(..., description="ID or name of existing service")
    endpoint: Dict[str, Any] = Field(..., description="Endpoint definition (path, method, description)")


# ── The Delta Output Expected from the LLM ──

class ArchitecturePatch(BaseModel):
    """The delta patch generated by the LLM for a new feature."""
    version_bump: Literal["minor", "patch"] = Field(
        default="minor",
        description="'minor' for feature addition (v1.0 -> v1.1), 'patch' for small fix"
    )
    feature_summary: str = Field(
        default="Architectural feature update",
        description="Concise description of the newly added feature"
    )

    @model_validator(mode="before")
    @classmethod
    def populate_feature_summary(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "feature_summary" not in data or not data["feature_summary"]:
                data["feature_summary"] = (
                    data.get("summary")
                    or data.get("description")
                    or data.get("title")
                    or data.get("feature")
                    or "Architectural feature update"
                )
        return data

    # 1. High-Level Design Additions
    added_nodes: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Newly synthesized HLD nodes (services, databases, gateways, queues)"
    )
    added_edges: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Newly synthesized interconnecting HLD edges"
    )

    # 2. Database Additions
    added_tables: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Newly added database tables"
    )
    added_columns: List[ColumnAddition] = Field(
        default_factory=list,
        description="Allowed additive columns on existing baseline tables"
    )
    added_relationships: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="New foreign key / relationship links"
    )

    # 3. Backend Additions
    added_services: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="Newly added backend services"
    )
    added_endpoints: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="New standalone API endpoints"
    )
    added_service_endpoints: List[ExistingServiceEndpointAddition] = Field(
        default_factory=list,
        description="New routes attached to existing baseline services"
    )

    # 4. Frontend Additions
    added_pages: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="New frontend pages or routes"
    )
    added_components: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="New UI components"
    )

    # 5. Security & Cloud Additions
    added_security_controls: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="New authentication/authorization policies or security controls"
    )
    added_cloud_resources: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="New cloud/infrastructure resources (queues, caches, topics)"
    )


# ── Verifier Results & Violations ──

class VerificationViolation(BaseModel):
    """A single rule violation detected during delta verification."""
    rule: str
    severity: Literal["CRITICAL", "ERROR", "WARNING"]
    target: str
    message: str


class PatchVerificationResult(BaseModel):
    """Overall outcome of running ArchitectureVerifier."""
    is_valid: bool
    violations: List[VerificationViolation] = Field(default_factory=list)

    def summary(self) -> str:
        if self.is_valid:
            return "✓ Patch verification passed with 0 violations."
        crit_count = sum(1 for v in self.violations if v.severity in ["CRITICAL", "ERROR"])
        return f"❌ Patch verification failed with {crit_count} blocking violations."


# ── Architecture Diff (Stored in DB for UI) ──

class ArchitectureDiff(BaseModel):
    """Machine-readable and user-facing diff between baseline and new version."""
    from_version: str
    to_version: str
    feature_prompt: str
    feature_summary: str

    added_nodes: List[Any] = Field(default_factory=list)
    added_edges: List[Dict[str, Any]] = Field(default_factory=list)
    added_tables: List[str] = Field(default_factory=list)
    added_columns: List[str] = Field(default_factory=list)
    added_endpoints: List[str] = Field(default_factory=list)

    baseline_stats: Dict[str, int] = Field(default_factory=dict)
    new_stats: Dict[str, int] = Field(default_factory=dict)
    invariance_certified: bool = Field(default=True, description="Whether all baseline components were preserved 100%")


# ── Version Context ──

class VersionContext(BaseModel):
    """Describes whether the current prompt initiates a new design or evolves an existing one."""
    mode: Literal["INITIAL", "EVOLUTION"]
    session_id: Optional[str] = None
    base_version: Optional[str] = None
    target_version: str = "1.0"
    parent_package: Optional[Dict[str, Any]] = None
